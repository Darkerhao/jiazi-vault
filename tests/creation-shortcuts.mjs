import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import electron from 'electron'
import { _electron } from 'playwright-core'
import { createVaultThroughUI } from './onboarding.mjs'

const root = process.cwd(), output = resolve(root, 'output/playwright/creation-shortcuts')
const data = resolve(output, `data-${Date.now()}`)
await mkdir(data, { recursive: true })
const app = await _electron.launch({ executablePath: electron, args: [resolve('tests/electron-launch.cjs')], cwd: root, env: { ...process.env, JIAZI_TEST_DATA: data } })
const page = await app.firstWindow()
page.setDefaultTimeout(15000)
const errors = [], passed = []
page.on('pageerror', (error) => errors.push(error.message))
const pass = (name) => { passed.push(name); console.log(`PASS ${name}`) }
const call = (command, args) => page.evaluate(({ command, args }) => window.jiaziVault.invoke(command, args), { command, args })
const clipboard = () => app.evaluate(async ({ clipboard }) => clipboard.readText())
const originalClipboard = await clipboard()
const modal = page.getByRole('dialog')
const button = (name) => modal.getByRole('button', { name, exact: true })
try {
  await createVaultThroughUI(page, 'shortcuts-fixture-password')
  await call('create_project', { project: { name: '已有项目' } })
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByPlaceholder('凭证名称', { exact: true }).fill('快捷新建测试')
  await page.getByPlaceholder('用户名', { exact: true }).fill('fixture-user')
  await page.getByPlaceholder('密码', { exact: true }).fill('original-fixture-password')
  await button('生成密码').click()
  await button('填入密码').waitFor()
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="生成安全密码"]')?.value.length === 20)
  await button('取消生成').click()
  assert.equal(await page.getByPlaceholder('密码', { exact: true }).inputValue(), 'original-fixture-password')
  await button('生成密码').click()
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="生成安全密码"]')?.value.length === 20)
  const generated = await page.getByPlaceholder('生成安全密码').inputValue()
  await button('填入密码').click()
  assert.equal(await page.getByPlaceholder('密码', { exact: true }).inputValue(), generated)
  pass('inline generation previews, cancels without replacing, and explicitly fills password')

  await button('新建项目').click()
  await page.getByPlaceholder('新项目名称').fill('不会创建的项目')
  await button('取消创建').click()
  assert.equal((await call('list_projects')).length, 1)
  assert.equal(await page.getByPlaceholder('密码', { exact: true }).inputValue(), generated)
  await button('新建项目').click()
  await page.getByPlaceholder('新项目名称').fill('已有项目')
  await button('创建并选中').click()
  await page.getByText('项目名称已存在，请选择已有项目或更换名称。', { exact: true }).waitFor()
  assert.equal(await page.getByPlaceholder('用户名', { exact: true }).inputValue(), 'fixture-user')
  assert.equal(await page.getByPlaceholder('密码', { exact: true }).inputValue(), generated)
  await page.getByPlaceholder('新项目名称').fill('就地创建项目')
  await button('创建并选中').click()
  await page.getByPlaceholder('新项目名称').waitFor({ state: 'hidden' })
  await modal.locator('.n-select').filter({ hasText: '就地创建项目' }).waitFor()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 600))
  await page.waitForFunction(() => innerWidth <= 900)
  await page.screenshot({ path: resolve(output, 'inline-project.png') })
  await button('保存').click()
  await modal.waitFor({ state: 'hidden' })
  const saved = (await call('list_items', {})).find((item) => item.title === '快捷新建测试')
  const full = await call('get_item', { id: saved.id, recordAccess: false })
  assert.equal(full.password, generated)
  assert.equal(full.username, 'fixture-user')
  assert.equal((await call('list_projects')).find((p) => p.id === full.projectId).name, '就地创建项目')
  pass('duplicate project retry preserves draft; created project is selected and saved with credential')

  await page.getByRole('button', { name: saved.title, exact: true }).click()
  await button('编辑凭证').click()
  await button('生成密码').click()
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="生成安全密码"]')?.value.length === 20)
  await button('填入密码').scrollIntoViewIfNeeded()
  await page.screenshot({ path: resolve(output, 'inline-generator-900.png') })
  assert.ok(await modal.evaluate((element) => element.scrollWidth <= element.clientWidth + 1))
  const replacement = await page.getByPlaceholder('生成安全密码').inputValue()
  await button('填入密码').click()
  await button('保存').click()
  await modal.waitFor({ state: 'hidden' })
  assert.equal((await call('get_item', { id: saved.id, recordAccess: false })).password, replacement)
  pass('existing credential password generation saves correctly at 900x600')

  const db = await call('create_item', { item: { type: 'database', title: '搜索数据库', username: 'db-user', password: 'db-secret', host: 'db.fixture.test', fields: { connectionString: 'postgres://fixture-connection' } } })
  await call('create_item', { item: { type: 'server', title: '搜索服务器', username: 'server-user', host: 'server.fixture.test' } })
  await page.keyboard.press('Control+k')
  const search = page.getByPlaceholder('搜索名称、项目、环境、账号…')
  await search.fill('搜索')
  await modal.getByRole('option').filter({ hasText: db.title }).hover()
  const select = page.getByRole('combobox', { name: '选择复制字段', exact: true })
  await select.locator('option[value="field:connectionString"]').waitFor({ state: 'attached' })
  assert.equal((await call('get_item', { id: db.id, recordAccess: false })).lastAccessedAt, undefined)
  for (const [field, expected] of [['username', 'db-user'], ['password', 'db-secret'], ['host', 'db.fixture.test'], ['field:connectionString', 'postgres://fixture-connection']]) {
    await select.selectOption(field)
    await button('复制').click()
    await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
    assert.equal(await clipboard(), expected)
    assert.ok((await modal.locator('[aria-selected="true"]').innerText()).includes(db.title))
  }
  assert.ok((await call('get_item', { id: db.id, recordAccess: false })).lastAccessedAt)
  assert.ok(!(await modal.innerText()).includes('db-secret'))
  await page.screenshot({ path: resolve(output, 'quick-copy.png') })
  pass('quick search copies username, password, host and connection string without opening details; usage updates retain selection')

  await search.fill('搜索服务器')
  await select.locator('option[value="host"]').waitFor({ state: 'attached' })
  assert.equal(await select.locator('option[value="password"]').count(), 0)
  assert.equal(await select.inputValue(), 'primary')
  await select.selectOption('host')
  await search.focus()
  await page.keyboard.press('Control+c')
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.equal(await clipboard(), 'server.fixture.test')
  await search.fill('没有匹配项')
  await page.getByText('没有匹配的凭证', { exact: true }).waitFor()
  assert.equal(await button('复制').isDisabled(), true)
  await call('lock_vault')
  await page.getByRole('heading', { name: '解锁保险库', exact: true }).waitFor()
  assert.equal(await page.getByRole('combobox', { name: '选择复制字段' }).count(), 0)
  assert.equal(await clipboard(), '')
  pass('changing results clears old fields; keyboard copies selected field; empty results disable copy; lock clears UI and clipboard')

  await page.getByPlaceholder('主密码', { exact: true }).fill('shortcuts-fixture-password')
  await page.getByRole('button', { name: '解锁', exact: true }).click()
  await page.getByRole('heading', { name: '全部条目', exact: true }).waitFor()
  await page.keyboard.press('Control+g')
  await page.getByRole('heading', { name: '密码生成器', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="生成安全密码"]')?.value.length === 20)
  await page.locator('.n-input-number input').fill('32')
  await page.locator('.n-input-number input').press('Tab')
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="生成安全密码"]')?.value.length === 32)
  const standalone = await page.getByPlaceholder('生成安全密码').inputValue()
  await page.getByRole('button', { name: '保存到保险库', exact: true }).click()
  assert.equal(await page.getByPlaceholder('密码', { exact: true }).inputValue(), standalone)
  await page.getByPlaceholder('凭证名称', { exact: true }).fill('独立生成器测试')
  await button('保存').click()
  await modal.waitFor({ state: 'hidden' })
  const standaloneItem = (await call('list_items', {})).find((item) => item.title === '独立生成器测试')
  assert.equal((await call('get_item', { id: standaloneItem.id, recordAccess: false })).password, standalone)
  pass('shared standalone generator changes length and saves the exact previewed password')

  await call('create_item', { item: { type: 'env', title: '搜索环境变量', environment: 'development', fields: { TOKEN: 'env-fixture-value', EMPTY: '' } } })
  await page.keyboard.press('Control+k')
  await search.fill('搜索环境变量')
  await select.locator('option[value="field:EMPTY"]').waitFor({ state: 'attached' })
  await select.selectOption('field:TOKEN')
  await button('复制').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.equal(await clipboard(), 'env-fixture-value')
  await select.selectOption('primary')
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }) })
  await button('复制').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.equal(await clipboard(), 'env-fixture-value')
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }) })
  await button('复制').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.ok((await clipboard()).includes('TOKEN='))
  assert.ok((await clipboard()).includes('EMPTY='))
  await select.selectOption('field:EMPTY')
  await button('复制').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.equal(await clipboard(), '')
  pass('quick search copies individual env values including empty strings and retains confirmation for full .env copy')
  assert.deepEqual(errors, [])
  await writeFile(resolve(output, 'report.json'), JSON.stringify({ passed, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: resolve(output, 'failure.png') }).catch(() => {})
  throw error
} finally {
  await app.evaluate(async ({ clipboard }, text) => clipboard.writeText(text), originalClipboard).catch(() => {})
  await app.close()
}
