import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import electron from 'electron'
import { _electron } from 'playwright-core'
import { createVaultThroughUI } from './onboarding.mjs'

const root = process.cwd(), output = resolve(root, 'output/playwright/product-experience')
const data = resolve(output, `data-${Date.now()}`)
await mkdir(data, { recursive: true })
const app = await _electron.launch({ executablePath: electron, args: [resolve('tests/electron-launch.cjs')], cwd: root, env: { ...process.env, JIAZI_TEST_DATA: data } })
const page = await app.firstWindow()
page.setDefaultTimeout(10000)
const errors = [], passed = []
page.on('pageerror', (error) => errors.push(error.message))
const pass = (name) => { passed.push(name); console.log(`PASS ${name}`) }
const call = (command, args) => page.evaluate(({ command, args }) => window.jiaziVault.invoke(command, args), { command, args })
async function section(name) {
  await page.getByRole('link', { name, exact: true }).click()
  await page.getByRole('heading', { name, exact: true }).waitFor()
}
async function choose(placeholder, label) {
  await page.locator('.filters .n-select').filter({ hasText: placeholder }).click()
  await page.locator('.n-base-select-menu').getByText(label, { exact: true }).click()
}
try {
  await createVaultThroughUI(page, 'experience-fixture-password')
  const project = await call('create_project', { project: { name: '客户管理平台', description: '财务系统', icon: '📁', color: '#c7ef68' } })
  const database = await call('create_item', { item: { type: 'database', title: '生产环境 PostgreSQL 主数据库', projectId: project.id, environment: 'production', host: 'postgresql-primary.internal.example.test', password: 'fixture-secret', port: 5432 } })
  await call('create_item', { item: { type: 'api-key', title: '过期 API', fields: { apiKey: 'api-fixture-only', expiresAt: '2000-01-01' } } })
  await section('项目')
  await page.getByPlaceholder('搜索当前项目…').fill('财务系统')
  await page.getByRole('button', { name: '客户管理平台', exact: true }).click()
  await page.getByRole('button', { name: database.title, exact: true }).waitFor()
  assert.equal(await page.getByPlaceholder('搜索当前凭证…').inputValue(), '')
  await section('设置')
  assert.equal(await page.getByRole('textbox', { name: '筛选当前列表' }).count(), 0)
  await section('全部条目')
  pass('project search does not filter credentials; settings has no inert local search')

  await page.getByRole('button', { name: database.title, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByText('凭证详情', { exact: true }).waitFor()
  assert.equal(await dialog.getByRole('textbox').count(), 0)
  assert.ok(!(await dialog.innerText()).includes('fixture-secret'))
  await dialog.getByRole('button', { name: '显示密码', exact: true }).click()
  assert.ok((await dialog.innerText()).includes('fixture-secret'))
  await dialog.getByRole('button', { name: '编辑凭证', exact: true }).click()
  await page.getByPlaceholder('端口', { exact: true }).fill('abc')
  await page.getByText('端口需为 0–65535 的整数。', { exact: true }).waitFor()
  assert.equal(await dialog.getByRole('button', { name: '保存', exact: true }).isDisabled(), true)
  await page.getByPlaceholder('端口', { exact: true }).fill('5433')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 600))
  await page.waitForFunction(() => innerWidth <= 900)
  const bounds = await dialog.getByRole('button', { name: '保存', exact: true }).evaluate((element) => ({ bottom: element.getBoundingClientRect().bottom, height: innerHeight }))
  assert.ok(bounds.bottom <= bounds.height, JSON.stringify(bounds))
  await page.screenshot({ path: resolve(output, 'editor-900.png') })
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal((await call('get_item', { id: database.id, recordAccess: false })).port, 5433)
  await page.waitForFunction(() => !document.querySelector('.n-spin-body'))
  assert.ok(await page.locator('.item-row').evaluateAll((rows) => rows.every((row) => row.getBoundingClientRect().right <= innerWidth && row.scrollWidth <= row.clientWidth + 1)))
  await page.screenshot({ path: resolve(output, 'vault-900.png') })
  pass('read-only details, port validation, compact rows and visible save at 900x600')

  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1200, 760))
  await section('全部条目')
  await choose('全部有效期', '已过期')
  await page.getByRole('button', { name: '过期 API', exact: true }).waitFor()
  assert.equal(await page.locator('.item-title').count(), 1)
  await page.getByRole('button', { name: '过期 API', exact: true }).click()
  await page.getByText('此 API Key 已过期，请向服务商确认并更新凭证。', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: '编辑凭证', exact: true }).click()
  await page.getByLabel('过期时间', { exact: true }).fill('2099-01-01')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByText('没有匹配的凭证', { exact: true }).waitFor()
  pass('expiry filter, warning, structured date edit and updated list')

  await section('设置')
  await page.getByText('本地加密的保护范围', { exact: true }).waitFor()
  const backupPath = resolve(data, 'safe.jvault')
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }) }, backupPath)
  await page.getByRole('button', { name: '创建加密备份', exact: true }).click()
  await page.getByText('内容修改已备份。', { exact: true }).waitFor()
  assert.equal((await call('get_backup_status')).hasChanges, false)
  await call('get_item', { id: database.id })
  assert.equal((await call('get_backup_status')).hasChanges, false)
  const savedStatus = await call('get_backup_status')
  await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
  assert.equal(await call('create_backup'), null)
  assert.deepEqual(await call('get_backup_status'), savedStatus)
  await section('全部条目')
  await page.locator('.item-row').filter({ hasText: database.title }).getByRole('button', { name: '收藏凭证', exact: true }).click()
  await page.getByText('有未备份的内容修改，建议更新备份。', { exact: true }).waitFor()
  assert.equal((await call('get_backup_status')).hasChanges, true)
  await section('设置')
  pass('successful backup updates reminder; usage stays clean and content changes become dirty')

  const importPath = resolve(data, 'review.json')
  await writeFile(importPath, JSON.stringify([
    { type: 'login', title: '导入样例', password: 'never-in-preview' },
    { type: 'login', title: '导入样例', password: 'never-in-preview' },
    { type: 'server', title: '坏端口', port: 99999 },
  ]))
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, importPath)
  const before = (await call('list_items', {})).length
  await page.getByRole('button', { name: '导入 JSON / CSV', exact: true }).click()
  await page.getByText('导入预览', { exact: true }).waitFor()
  assert.ok(!(await dialog.innerText()).includes('never-in-preview'))
  assert.equal((await call('list_items', {})).length, before)
  await page.waitForFunction(() => document.getAnimations().every((animation) => animation.playState !== 'running'))
  await page.screenshot({ path: resolve(output, 'import-preview.png') })
  await dialog.getByRole('button', { name: '导入 1 条有效记录', exact: true }).click()
  await page.getByText('已导入 1 条凭证', { exact: true }).waitFor()
  assert.equal((await call('list_items', {})).length, before + 1)
  await page.getByRole('button', { name: '导入 JSON / CSV', exact: true }).click()
  await dialog.getByRole('button', { name: '导入 0 条有效记录', exact: true }).waitFor()
  assert.equal(await dialog.getByRole('button', { name: '导入 0 条有效记录', exact: true }).isDisabled(), true)
  await dialog.getByRole('button', { name: '取消导入', exact: true }).click()
  const pending = await call('preview_import')
  await call('lock_vault')
  await page.getByRole('heading', { name: '解锁保险库', exact: true }).waitFor()
  await page.getByPlaceholder('主密码', { exact: true }).fill('experience-fixture-password')
  await page.getByRole('button', { name: '解锁', exact: true }).click()
  await page.getByRole('heading', { name: '全部条目', exact: true }).waitFor()
  await assert.rejects(call('confirm_import', { token: pending.token, skipDuplicates: true }), /IMPORT_EXPIRED/)
  pass('safe import preview, partial valid import, duplicate skipping, cancellation and lock invalidation')
  await app.evaluate(({ dialog }, path) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
    dialog.showMessageBox = async () => ({ response: 1 })
  }, backupPath)
  assert.equal(await call('restore_backup', { password: 'experience-fixture-password' }), true)
  await page.getByRole('heading', { name: '解锁保险库', exact: true }).waitFor()
  await page.getByPlaceholder('主密码', { exact: true }).fill('experience-fixture-password')
  await page.getByRole('button', { name: '解锁', exact: true }).click()
  await page.getByRole('heading', { name: '全部条目', exact: true }).waitFor()
  assert.deepEqual(await call('get_backup_status'), { lastBackupAt: null, hasChanges: true })
  assert.equal((await call('list_items', {})).length, 2)
  pass('restoring a backup restores credentials and resets device backup tracking')
  assert.deepEqual(errors, [])
  await writeFile(resolve(output, 'report.json'), JSON.stringify({ passed, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: resolve(output, 'failure.png') }).catch(() => {})
  throw error
} finally { await app.close() }
