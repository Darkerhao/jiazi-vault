import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import electron from 'electron'
import { _electron } from 'playwright-core'
import { createVaultThroughUI } from './onboarding.mjs'

const root = process.cwd(), output = resolve('output/playwright/operation-experience')
const data = join(output, `data-${Date.now()}`), password = 'operations-fixture-password'
await mkdir(data, { recursive: true })
let app, page
const passed = [], errors = []
const pass = (name) => { passed.push(name); console.log(`PASS ${name}`) }
async function launch() {
  app = await _electron.launch({ executablePath: electron, args: [resolve('tests/electron-launch.cjs')], cwd: root, env: { ...process.env, JIAZI_TEST_DATA: data } })
  page = await app.firstWindow()
  page.setDefaultTimeout(15000)
  page.on('pageerror', (error) => errors.push(error.message))
}
const call = (command, args) => page.evaluate(({ command, args }) => window.jiaziVault.invoke(command, args), { command, args })
const modal = () => page.getByRole('dialog')
const button = (name) => page.getByRole('button', { name, exact: true })
const clipboard = () => app.evaluate(({ clipboard }) => clipboard.readText())
async function section(name) {
  await page.getByRole('link', { name, exact: true }).click()
  await page.getByRole('heading', { name, exact: true }).waitFor()
}
async function unlock() {
  await page.getByPlaceholder('主密码', { exact: true }).fill(password)
  await button('解锁').click()
  await page.getByRole('heading', { name: '全部条目', exact: true }).waitFor()
}
async function selectOption(control, label) {
  await control.click()
  await page.locator('.n-base-select-option').filter({ hasText: new RegExp(`^${label}$`) }).click()
}
async function selectItems() {
  for (const title of ['目标', '批量B']) await page.getByRole('checkbox', { name: `选择${title}`, exact: true }).check()
}
async function backupUI(path) {
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, path)
  await button('从加密备份恢复').click()
  assert.equal(await page.getByPlaceholder('备份创建时使用的主密码').count(), 0)
  await button('选择备份文件').click()
  await page.getByPlaceholder('备份创建时使用的主密码').fill(password)
  await button('验证并预览').click()
  await button('确认替换并恢复').waitFor()
}

await launch()
const originalClipboard = await clipboard()
try {
  await createVaultThroughUI(page, password)
  await section('项目')
  await button('新建项目').click()
  await page.getByPlaceholder('项目名称', { exact: true }).fill('尚未保存的项目')
  await modal().getByRole('button', { name: '取消', exact: true }).click()
  await button('继续编辑').click()
  await button('放弃修改').waitFor({ state: 'hidden' })
  assert.equal(await page.getByPlaceholder('项目名称', { exact: true }).inputValue(), '尚未保存的项目')
  await page.keyboard.press('Escape')
  await button('放弃修改').click()
  await page.waitForFunction(() => document.querySelectorAll('[role="dialog"]').length === 0)
  assert.equal((await call('list_projects')).length, 0)
  pass('project cancellation and Escape protect changed fields; discard writes nothing')

  const groupA = await call('create_project', { project: { name: '原项目' } })
  const groupB = await call('create_project', { project: { name: '目标项目' } })
  const a = await call('create_item', { item: { type: 'database', title: '目标', username: 'fixture-user', password: 'a-fixture-secret', projectId: groupA.id, environment: 'development', tags: ['批量'], fields: { connectionString: 'postgres://fixture', dbName: 'fixture' } } })
  const b = await call('create_item', { item: { type: 'login', title: '批量B', password: 'b-fixture-secret' } })
  for (let i = 0; i < 55; i++) await call('create_item', { item: { type: 'login', title: `其他条目 ${i}`, username: '目标', password: `filler-${i}` } })
  await section('全部条目')
  await page.keyboard.press('Control+k')
  const search = page.getByPlaceholder('搜索名称、项目、环境、账号…')
  await search.fill('目标')
  await page.locator('.result').first().getByText('目标', { exact: true }).waitFor()
  await search.selectText()
  assert.equal(await search.evaluate((element) => element.value.slice(element.selectionStart, element.selectionEnd)), '目标')
  await search.press('Control+c')
  assert.equal(await search.evaluate((element) => element.value.slice(element.selectionStart, element.selectionEnd)), '目标')
  assert.equal(await app.evaluate(async ({ clipboard }) => {
    for (let i = 0; i < 50; i++) { if (clipboard.readText() === '目标') break; await new Promise((resolve) => setTimeout(resolve, 20)) }
    return clipboard.readText()
  }), '目标')
  await search.press('Control+Shift+c')
  await page.getByText('已复制到剪贴板', { exact: true }).waitFor()
  assert.equal(await clipboard(), 'a-fixture-secret')
  await button('查看全部 56 条结果').click()
  await page.getByText('共 56 条', { exact: true }).waitFor()
  assert.equal(await page.locator('.item-title').first().innerText(), '目标')
  pass('text copy and credential copy are separate; exact search ranks first and all results open the paginated list')

  await button('目标').click()
  await button('创建副本').click()
  assert.equal(await page.getByPlaceholder('凭证名称', { exact: true }).inputValue(), '目标（副本）')
  await page.getByPlaceholder('凭证名称', { exact: true }).fill('副本')
  await button('保存').click()
  await modal().waitFor({ state: 'hidden' })
  const clone = (await call('list_items', {})).find((item) => item.title === '副本')
  const original = await call('get_item', { id: a.id, recordAccess: false })
  const copied = await call('get_item', { id: clone.id, recordAccess: false })
  assert.notEqual(clone.id, a.id)
  assert.equal(copied.password, original.password)
  assert.deepEqual(copied.fields, original.fields)
  assert.deepEqual(copied.tags, original.tags)
  assert.equal(copied.projectId, original.projectId)
  assert.equal(copied.environment, original.environment)
  assert.equal(copied.lastAccessedAt, undefined)
  assert.equal((await call('list_item_history', { id: clone.id })).length, 0)
  pass('create-copy uses a new editor and preserves fields while giving a fresh identity and usage/history')

  await page.getByPlaceholder('搜索当前凭证…').fill('批量')
  await selectItems()
  await button('修改项目').click()
  await selectOption(modal().locator('.n-select'), '目标项目')
  await button('保存修改').click()
  await modal().waitFor({ state: 'hidden' })
  for (const id of [a.id, b.id]) assert.equal((await call('get_item', { id })).projectId, groupB.id)
  await selectItems()
  await button('修改环境').click()
  await selectOption(modal().locator('.n-select'), 'Testing')
  await button('保存修改').click()
  await modal().waitFor({ state: 'hidden' })
  for (const id of [a.id, b.id]) assert.equal((await call('get_item', { id })).environment, 'testing')
  assert.equal((await call('list_item_history', { id: a.id })).length, 2)
  await selectItems()
  await button('删除所选').click()
  await button('移入回收站').click()
  await page.getByRole('checkbox', { name: '选择目标', exact: true }).waitFor({ state: 'hidden' })
  await section('回收站')
  await selectItems()
  await button('恢复所选').click()
  await page.getByText('回收站是空的', { exact: true }).waitFor()
  pass('batch project/environment editing, history, trash and restore complete through the UI')

  const exportPath = join(data, 'project.json')
  await app.evaluate(({ dialog }, path) => {
    dialog.showMessageBox = async (_window, options) => { globalThis.exportConfirmation = options.detail; return { response: 1 } }
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: path })
  }, exportPath)
  await section('设置')
  await button('导出 JSON / CSV').click()
  await selectOption(modal().locator('.n-select').first(), '目标项目')
  await button('确认导出 2 条').click()
  await page.getByText('明文文件已保存：project.json', { exact: true }).waitFor()
  assert.deepEqual(JSON.parse(await readFile(exportPath, 'utf8')).map((item) => item.title).sort(), ['批量B', '目标'].sort())
  assert.ok((await app.evaluate(() => globalThis.exportConfirmation)).includes('共 2 条'))
  await section('全部条目')
  await page.getByPlaceholder('搜索当前凭证…').fill('批量')
  await page.getByRole('checkbox', { name: '选择目标', exact: true }).check()
  await button('导出所选').click()
  await button('确认导出 1 条').click()
  await modal().waitFor({ state: 'hidden' })
  assert.deepEqual(JSON.parse(await readFile(exportPath, 'utf8')).map((item) => item.title), ['目标'])
  pass('project and selected-item exports write only the confirmed records')

  await section('设置')
  await call('set_search_shortcut', { shortcut: null })
  assert.equal(await app.evaluate(({ globalShortcut }) => globalShortcut.register('CommandOrControl+Alt+Y', () => {})), true)
  const conflict = await call('set_search_shortcut', { shortcut: 'CommandOrControl+Alt+Y' })
  assert.equal(conflict.shortcutRegistered, false)
  await section('全部条目')
  await section('设置')
  await page.getByText(/注册失败，可能已被其他应用占用/).waitFor()
  const shortcutInput = page.getByRole('textbox', { name: '全局搜索快捷键', exact: true })
  await shortcutInput.click()
  await shortcutInput.press('Control+Alt+u')
  await button('保存快捷键').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.deepEqual(await call('get_desktop_status'), { shortcut: 'CommandOrControl+Alt+U', shortcutRegistered: true })
  await button('停用').click()
  await page.waitForFunction(() => !document.querySelector('.n-button--loading'))
  assert.equal((await call('get_desktop_status')).shortcut, null)
  assert.equal(await app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('CommandOrControl+Alt+U')), false)
  await app.evaluate(({ globalShortcut }) => globalShortcut.unregister('CommandOrControl+Alt+Y'))
  pass('shortcut conflicts are visible; UI records, registers and disables a custom shortcut')

  const backupPath = join(data, 'preview.jvault')
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }) }, backupPath)
  await call('create_backup')
  await call('update_item', { item: { ...await call('get_item', { id: a.id }), password: 'changed-after-backup' } })
  await backupUI(backupPath)
  assert.ok(!(await modal().innerText()).includes('a-fixture-secret'))
  assert.equal((await call('get_item', { id: a.id })).password, 'changed-after-backup')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 600))
  await page.locator('.n-message').last().waitFor({ state: 'hidden' })
  await page.screenshot({ path: join(output, 'backup-preview.png') })
  await modal().getByRole('button', { name: '取消', exact: true }).click()
  assert.equal((await call('get_item', { id: a.id })).password, 'changed-after-backup')
  await assert.rejects(call('restore_backup', { password }), /INVALID_BACKUP_PREVIEW/)
  const chosen = await call('select_backup_source', {})
  await assert.rejects(call('restore_backup', { token: chosen.token }), /INVALID_BACKUP_PREVIEW/)
  await assert.rejects(call('preview_backup', { token: chosen.token, password: 'incorrect-password' }), /BACKUP_RESTORE_FAILED/)
  const preview = await call('preview_backup', { token: chosen.token, password })
  assert.equal(preview.itemCount, 58)
  assert.equal(preview.projectCount, 2)
  assert.ok(!JSON.stringify(preview).includes('a-fixture-secret'))
  await call('lock_vault')
  await assert.rejects(call('batch_items', { ids: [a.id], action: { type: 'trash' } }), /VAULT_LOCKED/)
  await assert.rejects(call('restore_backup', { token: chosen.token }), /INVALID_BACKUP_PREVIEW/)
  await unlock()
  assert.equal((await call('get_item', { id: a.id })).password, 'changed-after-backup')
  pass('backup preview exposes only counts; cancellation, wrong passwords, unverified tokens and lock cannot replace data')

  await section('设置')
  await backupUI(backupPath)
  await writeFile(backupPath, 'changed after verification')
  await button('确认替换并恢复').click()
  await page.getByRole('heading', { name: '解锁保险库', exact: true }).waitFor()
  await unlock()
  assert.equal((await call('get_item', { id: a.id })).password, 'a-fixture-secret')
  assert.equal((await call('list_recovery_snapshots')).length, 1)
  assert.equal((await call('get_desktop_status')).shortcut, null)
  pass('confirmation restores exactly the verified backup, creates a rollback snapshot and preserves device shortcut preference')

  await app.close()
  await launch()
  await page.getByRole('heading', { name: '解锁保险库', exact: true }).waitFor()
  assert.equal((await call('get_desktop_status')).shortcut, null)
  await unlock()
  await page.getByPlaceholder('搜索当前凭证…').fill('批量')
  await page.locator('.n-spin-body').waitFor({ state: 'hidden' })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 600))
  await selectItems()
  await page.screenshot({ path: join(output, 'batch-list.png') })
  assert.deepEqual(errors, [])
  pass('device shortcut preference and credentials survive an actual app restart')
  await writeFile(join(output, 'report.json'), JSON.stringify({ passed, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: join(output, 'failure.png') }).catch(() => {})
  throw error
} finally {
  await app.evaluate(({ clipboard }, value) => clipboard.writeText(value), originalClipboard).catch(() => {})
  await app.close().catch(() => {})
}
